"""Generate a draft pipeline manifest from an inspected schema."""

from __future__ import annotations

import re
import textwrap
from pathlib import Path

import yaml

from polymorph.inspector import DatabaseSchema
from polymorph.manifest import Mode


def _slug(database: str | None) -> str:
    """Turn a database name or file path into a valid manifest name part."""
    base = Path(database).name if database else ""
    slug = re.sub(r"[^a-z0-9_-]+", "-", base.lower()).strip("-_")
    return slug or "database"


def render_manifest_draft(schema: DatabaseSchema, mode: Mode) -> str:
    """Render a draft manifest. Credentials are always ${ENV_VAR} placeholders."""
    engine = schema.engine
    if schema.server_version:
        engine += f" {schema.server_version}"

    # safe_dump quotes names only when YAML needs it (e.g. a table called "no").
    tables = yaml.safe_dump(
        [t.name for t in schema.tables], default_flow_style=False, sort_keys=False
    )

    return (
        "# Draft generated by `polymorph inspect --generate-manifest`.\n"
        "# Review it before running: remove tables you do not want to migrate.\n"
        "# Tables are listed in foreign-key order (parents before children).\n"
        f"# Source engine detected: {engine}\n"
        "version: 1\n"
        f"name: {_slug(schema.database)}-migration\n"
        f"mode: {mode.value}\n"
        "\n"
        "source:\n"
        "  url: ${SOURCE_URL}\n"
        "\n"
        "target:\n"
        "  url: ${TARGET_URL}\n"
        "\n"
        "settings:\n"
        "  batch_size: 1000\n"
        "\n"
        "tables:\n"
        f"{textwrap.indent(tables, '  ')}"
    )